from __future__ import annotations

from typing import Any, Protocol


class GraphPort(Protocol):
    def nodes(self) -> list[str]: ...
    def edges(self) -> list[tuple[str, str, float]]: ...
    def has_node(self, id: str) -> bool: ...


class DispatcherPort(Protocol):
    graph: GraphPort

    def submit_request(self, pickup_node: str, dropoff_node: str) -> Any: ...
    def add_driver(self, name: str, node: str) -> Any: ...
    def update_driver(self, driver_id: str, name: str | None = None,
                      node: str | None = None) -> Any: ...
    def remove_driver(self, driver_id: str) -> bool: ...
    def dispatch_next(self, strategy: Any) -> Any | None: ...
    def complete_trip(self, trip_id: str) -> bool: ...
    def can_undo(self) -> bool: ...
    def can_redo(self) -> bool: ...
    def undo(self) -> bool: ...
    def redo(self) -> bool: ...
    def queue_snapshot(self) -> list[Any]: ...
    def trips_snapshot(self) -> list[Any]: ...
    def drivers_snapshot(self) -> dict[str, Any]: ...
    def export_state(self) -> dict: ...


class StoragePort(Protocol):
    def load_all(self) -> dict: ...
    def save_all(self, state: dict) -> None: ...


# Tên thuộc tính/phương thức bắt buộc của Dispatcher thật (dùng để tự nhận biết backend).
DISPATCHER_REQUIRED = (
    "submit_request", "add_driver", "update_driver", "remove_driver", "dispatch_next",
    "complete_trip", "can_undo", "can_redo", "undo", "redo",
    "queue_snapshot", "trips_snapshot", "drivers_snapshot", "export_state", "from_state",
)
